"""Generate all catalog views from one source. Run with --check in CI."""
from __future__ import annotations

import argparse
import json
from collections import Counter
from catalog import ROOT, load, sort_key, validate_records


def esc(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def link(r):
    return f"[{r['title']}](papers.md#{r['id']})"


def generate():
    meta, records, routes = load("collection.json"), load(), load("routes.json")
    errors = validate_records(records, meta)
    if errors:
        raise ValueError("\n".join(errors))
    records = sorted(records, key=sort_key, reverse=True)
    by_id = {r["id"]: r for r in records}
    counts = Counter(r["kind"] for r in records)
    depths = Counter(r["review_depth"] for r in records)
    banner = "<!-- Generated by scripts/render.py. Edit data/ and templates/, then regenerate. -->\n\n"
    papers = [banner, "# Annotated research catalog\n", "[Overview](../README.md) · [Topics](topics.md) · [Reading routes](reading-routes.md) · [Explorer](https://duyvuleo.github.io/awesome-agents-that-learn/)\n", f"{len(records)} unique works. Source inspection date: {meta['updated']}. Dates use first linked preprint submission when available; venue status is recorded separately. Full-text means selected relevant sections were inspected, not a complete peer review. No paper's results were independently reproduced for this collection.\n"]
    for r in records:
        sources = " · ".join(f"[Source {i+1}]({url})" for i, url in enumerate(r["sources"]))
        code = f"[Official artifact]({r['code_url']}) — {r['code_note']}" if r["code_url"] else r["code_note"]
        papers.extend([f"<a id=\"{r['id']}\"></a>\n\n## {r['title']}\n", f"**{r['date']} · {r['status']}" + (f" · {r['venue']}" if r["venue"] else "") + f" · {r['scope']} · {r['kind']}**\n", f"[Primary source]({r['url']})\n", f"**Mechanism.** {r['mechanism']}\n", f"**What changes:** {', '.join(meta['update_targets'][t] for t in r['update_targets'])}. **Persistence:** {r['persistence']}. **Learning signal:** {r['learning_signal']}\n", f"**Evaluation.** {r['evaluation']}\n"])
        papers.extend([f"**Boundary.** {r['limitations']}\n", f"**Code / data.** {code}\n", f"**Topics:** {', '.join(r['topics'])}. **Reviewed:** {r['review_depth']} · {r['checked']}.\n", f"{sources}\n"])
    topics = [banner, "# Papers by topic\n", "[Overview](../README.md) · [Full annotations](papers.md)\n", "A work may appear in several topics; counts here are not additive.\n"]
    for topic, title in meta["topics"].items():
        selected = [r for r in records if topic in r["topics"]]
        topics.append(f"<a id=\"{topic}\"></a>\n\n## {title} ({len(selected)})\n")
        topics.extend(f"- {r['date']} — {link(r)} · {r['scope']} · {r['status']}\n" for r in selected)
        topics.append("\n")
    by_year = [banner, "# Papers by year\n", "[Overview](../README.md) · [Full annotations](papers.md)\n"]
    for year in sorted({r["year"] for r in records}, reverse=True):
        by_year.append(f"## {year}\n")
        by_year.extend(f"- {r['date']} — {link(r)}\n" for r in records if r["year"] == year)
        by_year.append("\n")
    bench = [banner, "# Benchmarks and evaluation resources\n", "[Overview](../README.md) · [Evaluation guide](evaluation-guide.md)\n", "These are benchmark papers, not a count of independently inspected dataset releases. A code link does not certify completeness or reproduce a score. Memory recall and sustained improvement measure different outcomes.\n", "| Work | What it tests | What it does not establish |\n| --- | --- | --- |\n"]
    for r in records:
        if r["kind"] == "benchmark":
            bench.append(f"| {link(r)} | {esc(r['evaluation'])} | {esc(r['limitations'])} |\n")
    code = [banner, "# Official code and data links\n", "[Overview](../README.md) · [Full annotations](papers.md)\n", "Links were inspected as public primary sources. No linked project was installed or executed for this release. Check the original license, dataset access, cost, environment, and version before use.\n", "| Work | Artifact | Inspection note |\n| --- | --- | --- |\n"]
    for r in records:
        if r["code_url"]:
            code.append(f"| {link(r)} | [Open]({r['code_url']}) | {esc(r['code_note'])} |\n")
    reading = [banner, "# Choose a reading route\n", "[Overview](../README.md) · [Primer](primer.md) · [Evaluation guide](evaluation-guide.md)\n", "These are suggested study sequences, not rankings. Read the mechanism and evaluation boundary together; follow the linked primary paper for the full argument.\n"]
    for route in routes:
        reading.extend([f"<a id=\"{route['id']}\"></a>\n\n## {route['title']}\n", route["question"] + "\n"])
        for i, item in enumerate(route["steps"], 1):
            r = by_id[item["paper"]]
            reading.append(f"{i}. **{link(r)}** — {item['why']}\n")
        reading.append(f"\n**Study exercise:** {route['exercise']}\n")
    template = (ROOT / "templates" / "README.md").read_text()
    featured = [by_id[x] for x in ["voyager", "expel", "dspy", "darwin-godel-machine", "seal", "agentstream"] if x in by_id]
    featured_table = "| Work | Learn this idea |\n| --- | --- |\n" + "".join(f"| [{r['title']}](docs/papers.md#{r['id']}) | {esc(r['mechanism'])} |\n" for r in featured)
    stats = f"**{len(records)} annotated works** · {counts['paper']} papers · {counts['survey']} surveys · {counts['benchmark']} benchmark papers · **{len(routes)} reading routes**"
    depth_text = f"{depths['full-text']} entries include inspection of selected full-text sections; {depths['abstract']} are based on primary abstracts/metadata" + (f"; {depths['project']} use project documentation" if depths['project'] else "") + "."
    readme = banner + template.replace("{{STATS}}", stats).replace("{{UPDATED}}", meta["updated"]).replace("{{DEPTH}}", depth_text).replace("{{FEATURED}}", featured_table)
    payload = {"meta": meta, "papers": records, "routes": routes}
    # Escape '<' so a source title cannot close the script element when embedded.
    catalog_js = "// Generated; edit data/.\nwindow.CATALOG = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c") + ";\n"
    outputs = {"README.md": readme, "docs/papers.md": "\n".join(papers), "docs/topics.md": "".join(topics), "docs/by-year.md": "".join(by_year), "docs/benchmarks.md": "".join(bench), "docs/code.md": "".join(code), "docs/reading-routes.md": "\n".join(reading), "site/catalog.js": catalog_js, "site/catalog.json": json.dumps(payload, ensure_ascii=False, indent=2) + "\n"}
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Stale generated files: " + ", ".join(stale))
    print("Generated views are current." if args.check else "Generated catalog, reading routes, and explorer data.")


if __name__ == "__main__":
    main()
